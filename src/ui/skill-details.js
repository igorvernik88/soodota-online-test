const percent = new Set(["strength", "speed", "pen", "chance"]);
const seconds = new Set([
  "duration",
  "cooldown",
  "incoming",
  "interval",
  "delay",
  "window",
  "reduction",
  "minimum",
  "recharge",
  "burn",
]);
export function skillDetails(id, rank, icon, hotkey) {
  const skill = SKILLS[id],
    ranks = skill.ranks;
  const rows = Object.keys(ranks[0])
    .map(
      (key) =>
        `<div class="skill-stat"><span>${key === "projectileSpeed" && id === "headOn" ? "Скорость рывка" : key === "projectileSpeed" && id === "throwOka" ? "Скорость полёта" : labels[key] || key}</span><span>${ranks.map((p, i) => `<b class="${i + 1 === rank ? "current-rank" : ""}">${percent.has(key) ? Math.round(p[key] * 100) + "%" : p[key]}${seconds.has(key) ? "с" : ""}</b>`).join(" / ")}</span></div>`,
    )
    .join("");
  return `<header>${icon}<div><strong>${skill.name}</strong><small>${hotkey ? "Активный · " + hotkey : "Пассивный"}</small></div></header><p>${descriptions[id] || skill.name}</p><div class="skill-ranks">${ranks.map((_, i) => `<i class="${i < rank ? "learned" : ""}">${i + 1}</i>`).join("")}</div>${rows}`;
}
